import fs from 'node:fs';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),'utf8');
const contracts=JSON.parse(read('registry/event-contracts.json'));
const fabric=JSON.parse(read('registry/event-fabric.json'));
const checks=[]; const ok=(name,v)=>{if(!v)throw new Error(`FAIL: ${name}`);checks.push(name)};
let uuid=0;
const sandbox={console,crypto:{randomUUID:()=>`uuid-${++uuid}`},CustomEvent:class{constructor(type,o){this.type=type;this.detail=o?.detail}},window:{dispatchEvent(){},CasaCore:{modules:{register(){}},emit(){}},CasaAudit:{record(){}}},fetch:async url=>({ok:true,json:async()=>String(url).includes('event-fabric')?fabric:contracts}),setTimeout,clearTimeout,queueMicrotask};
sandbox.window.window=sandbox.window;vm.createContext(sandbox);vm.runInContext(read('core/casa-events.js'),sandbox);await sandbox.window.CasaEvents.loadContracts();
const api=sandbox.window.CasaEvents;
ok('runtime version 3',api.VERSION==='3.0.0');
ok('fabric alias',sandbox.window.CasaEventFabric===api);
const first=api.publish('experience.started',{experience_id:'one',touchpoint:'web'},{source:{service:'test',version:'1'}});
const second=api.publish('experience.started',{experience_id:'two',touchpoint:'web'},{source:{service:'test',version:'1'}});
ok('ordered same partition',first.partition==='experience'&&second.sequence===first.sequence+1);
ok('integrity verifies',api.verify(first)===true);
const tampered={...first,payload:{experience_id:'tampered',touchpoint:'web'}};
ok('tampering detected',api.verify(tampered)===false);
const replay=api.replay({partition:'experience',from_sequence:first.sequence,to_sequence:second.sequence});
ok('deterministic replay',replay.length===2&&replay[0].id===first.id&&replay[1].id===second.id);
let delivered=0;
api.registerConsumer({id:'successful-consumer',event_types:['experience.started'],handler:async()=>{delivered++}});
const third=api.publish('experience.started',{experience_id:'three',touchpoint:'web'},{source:{service:'test',version:'1'}});
await new Promise(r=>setTimeout(r,10));
ok('consumer delivered',delivered===1);
ok('checkpoint after success',api.checkpoint('successful-consumer','experience')===third.sequence);
api.registerConsumer({id:'failed-consumer',event_types:['knowledge.updated'],max_attempts:2,handler:async()=>{throw new Error('expected')}});
const failed=api.publish('knowledge.updated',{resource_id:'k1',change_type:'updated'},{source:{service:'test',version:'1'}});
await new Promise(r=>setTimeout(r,10));
ok('failed consumer not checkpointed',api.checkpoint('failed-consumer',failed.partition)===0);
ok('dead letter evidence',api.deadLetters().some(x=>x.consumer_id==='failed-consumer'&&x.event.id===failed.id&&x.attempts===2));
const snapshot=api.snapshot();
ok('snapshot describes fabric',snapshot.append_only&&snapshot.replayable&&snapshot.integrity_verification&&snapshot.dead_letter_count===1);
ok('fabric policy adapter ready',fabric.principles.transport_neutral&&fabric.replay_contract.preserves_original_envelope);
console.log(`${checks.length} Event Fabric checks passed`);
