import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const json=p=>JSON.parse(read(p));
const manifest=json('platform-manifest.json');
const deployment=json('deployment-manifest.json');
const validation=json('release-validation.json');
const notes=json('release-notes.json');
const worker=read('_worker.js');
const control=read('control/index.html');
const publicHtml=read('index.html');
const failures=[];
const check=(ok,msg)=>{if(!ok) failures.push(msg)};
const workerPlatform=worker.match(/platform_version:\s*"([^"]+)"/)?.[1];
const workerVersion=worker.match(/worker_version:\s*"([^"]+)"/)?.[1];
const workerBuild=worker.match(/build:\s*"([^"]+)"/)?.[1];
check(workerPlatform===manifest.platform_version,`Worker platform ${workerPlatform} != manifest ${manifest.platform_version}`);
check(workerVersion===manifest.worker_version,`Worker identity ${workerVersion} != manifest ${manifest.worker_version}`);
check(workerBuild===manifest.build,`Worker build ${workerBuild} != manifest ${manifest.build}`);
check(deployment.platform_version===manifest.platform_version,'Deployment manifest platform version mismatch');
check(deployment.release===manifest.platform_version,'Deployment release mismatch');
check(validation.platform_version===manifest.platform_version,'Release validation platform version mismatch');
check(notes.platform_version===manifest.platform_version,'Release notes platform version mismatch');
check(control.includes(`data-expected-platform="${manifest.platform_version}"`),'Control Center expected platform mismatch');
check(control.includes(`data-expected-build="${manifest.build}"`),'Control Center expected build mismatch');
check(publicHtml.includes(`content="${manifest.build}" name="casa-amar-build"`),'Public website build metadata mismatch');
check(!control.includes('v2026.07.24.179')&&!control.includes('v2026.07.24.180'),'Control Center contains stale release identity');
check(!worker.includes('v2026.07.24.179')&&!worker.includes('v2026.07.24.180'),'Worker contains stale release identity');
if(failures.length){console.error('Deployment Identity Governance FAILED'); for(const f of failures) console.error(`- ${f}`); process.exit(1)}
console.log(`Deployment Identity Governance VERIFIED: ${manifest.platform_version} / ${manifest.worker_version} / ${manifest.build}`);
