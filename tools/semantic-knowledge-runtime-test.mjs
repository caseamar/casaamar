import fs from 'node:fs';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),'utf8');
const registry=JSON.parse(read('registry/semantic-knowledge.json'));
const events=[];
const sandbox={console,Date,Map,Set,Promise,JSON,Number,String,Array,Math,CustomEvent:class{constructor(type,o){this.type=type;this.detail=o?.detail}},fetch:async()=>({ok:true,json:async()=>registry}),window:{dispatchEvent(){},CasaEvents:{publish:(type,payload)=>events.push({type,payload})},CasaCore:{modules:{register(){}}}}};
sandbox.window.window=sandbox.window;
vm.createContext(sandbox);
vm.runInContext(read('core/casa-semantic-knowledge.js'),sandbox);
const runtime=sandbox.window.CasaSemanticKnowledge;
await runtime.load({force:true});
const fail=[],check=(ok,msg)=>{if(!ok)fail.push(msg)};
const health=runtime.validate();
check(runtime.version==='1.0.0','runtime version');
check(health.valid===true,'registry integrity');
check(health.counts.claims===4&&health.counts.evidence===4,'claim and evidence counts');
const result=runtime.search('policy fail closed',{minimum_confidence:0.8});
check(result[0]?.id==='claim-policy-fail-closed','deterministic semantic retrieval');
const provenance=runtime.provenance('claim-policy-fail-closed');
check(provenance?.evidence?.[0]?.source?.id==='source-policy-runtime','provenance resolves source');
const context=runtime.assembleContext('industry neutral core',{minimum_confidence:0.9});
check(context.claims.length>=1&&context.average_confidence>=0.9,'AI context assembly is evidence-backed');
check(context.retrieval_mode==='deterministic-lexical-fallback','provider-neutral retrieval fallback');
const lineage=runtime.lineage('claim-metadata-authoritative',{direction:'out',depth:2});
check(lineage.relations.some(x=>x.to==='claim-core-industry-neutral'),'lineage traversal');
check(events.some(x=>x.type==='knowledge-runtime:ready'),'ready event emitted');
const broken=structuredClone(registry);broken.claims[0].evidence_ids=['missing'];
check(runtime.validate(broken).valid===false,'unknown evidence fails validation');
if(fail.length){console.error('Semantic Knowledge Runtime FAILED\n- '+fail.join('\n- '));process.exit(1)}
console.log(`Semantic Knowledge Runtime VERIFIED: ${health.counts.claims} claims, ${health.counts.evidence} evidence items, provenance, lineage and governed AI context assembly`);
